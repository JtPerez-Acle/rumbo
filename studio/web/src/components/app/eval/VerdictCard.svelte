<script>
  /* A comprehension check reports a STATE OF UNDERSTANDING, not a grade.
   *
   * The explain step is diagnostic, and scoring it punished correct-but-generic
   * explanations — a concept is generic by nature. Work products keep numbers;
   * this does not. Legacy explains scored under the old numeric rubric render
   * here too, with no badge: we never show that number again rather than invent
   * a verdict for it.
   */
  import Icon from '../Icon.svelte';
  import ReadingCard from './ReadingCard.svelte';
  import { postWithTimeout } from '../../../lib/api.js';
  import { renderMarkdownUntrusted } from '../../../lib/untrusted.js';
  import { VERDICT } from '../../../lib/verdicts.js';

  let { ev, nodeId } = $props();

  let reteaching = $state(false);
  let reteach = $state(null);
  let reteachError = $state('');
  let asked = $state(0);

  const label = $derived(VERDICT[ev.verdict]);
  /* The third move. "casi"/"todavía no" used to leave exactly two options —
     retry with the same understanding, or skip — which is no choice at all for
     someone who did not follow the video. Asking for help is free: never
     evaluated, never counted, and it cannot lower anything. */
  const canReteach = $derived(ev.verdict === 'casi' || ev.verdict === 'todavia_no');

  async function askAgain() {
    reteaching = true;
    reteachError = '';
    reteach = null;
    const { res, data } = await postWithTimeout('/api/learn/reteach', { node_id: nodeId });
    reteaching = false;
    if (!res || !res.ok) {
      reteachError = (data && data.detail) || 'No pudimos prepararla, intenta de nuevo.';
      return;
    }
    reteach = data;
    asked += 1;
  }
</script>

<div class="card" style="margin-top:4px">
  <div class="row" style="justify-content:space-between;align-items:center;margin-bottom:10px">
    <div class="microlabel" style="color:var(--amber)">
      ¿Quedó claro?{ev.attempt && ev.attempt > 1 ? ` · intento ${ev.attempt}` : ''}
    </div>
    {#if label}<div class={`verdict ${ev.verdict}`}>{label}</div>{/if}
  </div>

  <p class="t-base">{ev.feedback || ''}</p>

  {#if ev.misconception}
    <div class="note note-warn"><Icon name="alert" class="ic ic-s" /> {ev.misconception}</div>
  {/if}

  {#if ev.missing?.length}
    <div class="note note-goal">
      <b><Icon name="target" class="ic ic-s" />
        {ev.verdict === 'lo_tienes' ? 'Para redondearlo:' : 'Para que quede claro te falta:'}</b>
      <ul style="margin:6px 0 0 18px">
        {#each ev.missing as m}<li style="margin-bottom:4px">{m}</li>{/each}
      </ul>
    </div>
  {/if}

  {#if canReteach}
    {#if reteaching}
      <ReadingCard message="Tu tutora está buscando otra manera de explicártelo…" />
    {/if}

    {#if reteach}
      <div class="card-spot" style="margin-top:10px">
        <div class="eyebrow"><Icon name="spark" class="ic ic-s" /> Otra forma de verlo</div>
        <!-- Generated by writer.py, but model output all the same: sanitised. -->
        <div class="written" style="margin-top:8px">{@html renderMarkdownUntrusted(reteach.explanation)}</div>
        {#if reteach.check}
          <div class="note note-goal" style="margin-top:10px"><b>Para comprobar:</b> {reteach.check}</div>
        {/if}
      </div>
    {/if}

    {#if reteachError}
      <p class="faint t-sm" style="margin-top:8px">{reteachError}</p>
    {/if}

    <button class="btn btn-ghost btn-sm" style="width:100%;margin-top:10px"
            disabled={reteaching} onclick={askAgain}>
      <Icon name="spark" class="ic ic-s" />
      {asked ? 'Explícamelo otra vez, distinto' : 'Explícamelo de otra forma'}
    </button>
  {/if}
</div>
